#!/bin/bash

# =================================================================
# 黄金智能走势预测与波段风控系统 - 一键启动脚本
# =================================================================

# 切换到项目绝对目录
PROJECT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$PROJECT_DIR"

echo "================================================="
echo " 🚀 正在启动 黄金智能走势预测与波段风控系统..."
echo "================================================="

# 检查虚拟环境
VENV_PYTHON="$PROJECT_DIR/.venv/bin/python"
if [ ! -f "$VENV_PYTHON" ]; then
    echo "❌ 错误: 未检测到 Python 虚拟环境 ($VENV_PYTHON)"
    echo "请先在项目根目录运行 uv 或 python3 -m venv .venv 创建环境。"
    exit 1
fi

# 检查并释放端口 8080 (防止多进程冲突)
PID=$(lsof -ti :8080)
if [ -n "$PID" ]; then
    echo "⚠️ 检测到端口 8080 已被进程 $PID 占用，正在释放端口..."
    kill -9 $PID 2>/dev/null
    sleep 1
fi

# 启动 Flask 服务
echo "🌐 启动 Web 预测引擎服务..."
"$VENV_PYTHON" app.py &
SERVER_PID=$!

# 等待服务就绪
echo "⌛ 正在加载 5 年历史高维数据与神经网络引擎..."
sleep 3

# 自动在默认浏览器中打开系统界面
URL="http://127.0.0.1:8080"
echo "🎉 服务启动成功！正在自动打开浏览器: $URL"
open "$URL"

echo "================================================="
echo " 💡 系统正常运行中！按 Ctrl+C 可停止服务。"
echo "================================================="

# 挂起保持终端服务运行
wait $SERVER_PID
